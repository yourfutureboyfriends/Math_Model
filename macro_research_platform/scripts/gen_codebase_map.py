"""
Generate docs/CODEBASE_MAP.md: every backend module and frontend file with the first line of its own docstring /
header comment, grouped by folder — so anything can be found by what it does. Re-run after adding modules:

    python scripts/gen_codebase_map.py

Files without a description are listed at the end, so they can be given one.
"""
from __future__ import annotations

import ast
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CODEBASE_MAP.md"
SKIP = {"__pycache__", "node_modules", "alembic", "dist", ".vite"}
LEGACY = {
    "src": "pre-API research library (Streamlit era); api/main.py still imports a few models from src.models",
    "dashboard.py": "legacy Streamlit dashboard (`make dashboard`)",
    "pipeline.py": "legacy batch data pipeline",
    "settings.py": "legacy settings for the Streamlit-era modules",
    "validation_runner.py": "legacy validation runner",
    "database": "legacy SQLite database helpers",
    "api/asgi.py": "old entry point run from inside api/ (the app starts from api.main)",
    "api/equity_router.py": "old entry point run from inside api/",
}
SEPARATE = ("api/quant/optengine", "api/routers/options_engine.py")   # the options decision engine (its own project)


def py_summary(p: Path) -> str:
    try:
        doc = ast.get_docstring(ast.parse(p.read_text(errors="ignore")))
    except SyntaxError:
        return ""
    if not doc:
        return ""
    para = " ".join(doc.strip().split("\n\n")[0].replace("-\n", "-").split())          # the first paragraph, on one line
    return para if len(para) <= 220 else para[:217].rsplit(" ", 1)[0] + "…"


def ts_summary(p: Path) -> str:
    text = p.read_text(errors="ignore")
    m = re.match(r"\s*/\*\*?\s*\n?\s*\*?\s*(.+?)\s*(\n|\*/)", text)
    if m and not m.group(1).startswith("@"):
        return m.group(1).strip(" *")
    m = re.match(r"\s*//\s*(.+)", text)
    return m.group(1).strip() if m else ""


def collect(base: Path, exts, summary) -> dict:
    groups = defaultdict(list)
    for p in sorted(base.rglob("*")):
        if p.suffix not in exts or SKIP & set(p.parts) or p.name == "__init__.py":
            continue
        rel = p.relative_to(ROOT)
        if "tests" in rel.parts or rel.parts[-1].endswith((".test.ts", ".test.tsx", ".d.ts")):
            continue
        groups[str(rel.parent)].append((rel.name, summary(p)))
    return groups


def section(title: str, groups: dict, lines: list, missing: list) -> None:
    lines.append(f"\n## {title}\n")
    for folder in sorted(groups):
        lines.append(f"\n### `{folder}/`\n")
        lines.append("| File | What it does |\n|---|---|")
        for name, desc in groups[folder]:
            rel = f"{folder}/{name}"
            legacy = LEGACY.get(rel)
            text = (f"*legacy* — {legacy}" if legacy else desc) or "—"
            if not desc and not legacy and not rel.startswith(SEPARATE):
                missing.append(rel)
            if not desc and rel.startswith(SEPARATE):
                text = "options decision engine (separate project — see docs/options_decision_engine.md)"
            lines.append(f"| `{name}` | {text.replace('|', '\\|')} |")


def main() -> None:
    lines = ["# Codebase map", "",
             "Generated by `scripts/gen_codebase_map.py` from each file's own docstring / header comment — re-run it "
             "after adding files. Start points: the API app is `api/main.py` (routers in `api/routers/`), business "
             "logic sits in topic modules under `api/`, pure maths in `api/calculations/`, and the UI's panels in "
             "`frontend/src/components/sections/`.", "",
             "## Where things live", "",
             "| Area | Location |", "|---|---|",
             "| App entry, startup jobs, older endpoints | `api/main.py` |",
             "| Endpoints by topic | `api/routers/*.py` |",
             "| Shared router helpers (auth, capabilities, errors, audit) | `api/core/web.py` |",
             "| Sign-in, accounts, two-factor, access rules | `api/core/` |",
             "| Funds, positions & tiers, governance | `api/funds.py`, `api/positions.py`, `api/governance*.py` |",
             "| Fund book: positions, orders, blotter, NAV | `api/portfolio_store.py`, `api/blotter_store.py`, `api/fund_store.py` |",
             "| Pure calculations (risk, VaR, attribution, metrics) | `api/calculations/` |",
             "| Quant Lab & LEAN | `api/quant/` |",
             "| Market data & providers | `api/marketdata/`, `api/providers/` |",
             "| Broker links (IBKR, Alpaca) | `api/brokerage/` |",
             "| UI panels | `frontend/src/components/sections/<area>/` |",
             "| UI shared helpers (fetch, formatting, fund brand) | `frontend/src/lib/` (`http.ts`, `format.ts`, `fundBrand.ts`) |",
             "| Tests | `api/tests/`, `frontend/src/test/` |", "",
             "Legacy (kept, not part of the running app): " + "; ".join(f"`{k}` — {v}" for k, v in LEGACY.items()) + "."]
    missing: list = []
    section("Backend (`api/`)", collect(ROOT / "api", {".py"}, py_summary), lines, missing)
    section("Frontend (`frontend/src/`)", collect(ROOT / "frontend" / "src", {".ts", ".tsx"}, ts_summary), lines, missing)
    lines += ["", f"## Files without a description ({len(missing)})", ""] + [f"- `{m}`" for m in missing]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} — {len(missing)} files without a description")


if __name__ == "__main__":
    main()
